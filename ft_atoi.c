int	ft_atoi(char *str)
{
	int	i;
	int	signe;
	int	res;

	signe = 1;
	i = 0;
	if (str[i] == '+' || str[i] == '-')
	{
		if(str[i] == '-')
		{
			signe = -1;
		}
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		res = res * 10 + (str[i] - '0');
		i++;
	}
	return (res * signe);
}
